/* ПР 2. Параметри тріщиностійкості (ЛМР, ПМР, закон Паріса) */
registerPR({
  id: 2, module: 1,
  title: 'Розрахунок параметрів тріщиностійкості деталей методами механіки руйнування',
  short: 'Механіка руйнування',
  gen(r) {
    const geo = r.pick(['edge', 'center']);
    const Y = geo === 'edge' ? 1.12 : 1.0;
    const sigma = r.step(120, 260, 10);
    const amm = r.step(3, 16, 0.5);                       // розрахункова довжина (для центральної — півдовжина)
    const a = amm / 1000;
    const K = Y * sigma * Math.sqrt(Math.PI * a);
    const KIC = Math.round(K * r.uni(0.85, 2.6));
    const sy = r.step(450, 1100, 50);
    const B = r.step(8, 40, 2);
    const nK = KIC / K, sc = KIC / (Y * Math.sqrt(Math.PI * a));
    const ac = (KIC / (Y * sigma)) ** 2 / Math.PI * 1000;   // мм
    const rp = (K / sy) ** 2 / (2 * Math.PI) * 1000;         // мм
    const Bmin = 2.5 * (KIC / sy) ** 2 * 1000;               // мм
    const C = 6.9e-12, m = 3;
    const Np = ac > amm ? 2 / (C * (Y * sigma * Math.sqrt(Math.PI)) ** m) * (1 / Math.sqrt(a) - 1 / Math.sqrt(ac / 1000)) : 0;
    const nadm = 1.5, sadm = sc / nadm;
    return { geo, Y, sigma, amm, a, K, KIC, sy, B, nK, sc, ac, rp, Bmin, C, m, Np, nadm, sadm };
  },
  build(v, r) {
    const b = [];
    const G = v.geo === 'edge' ? 'крайова наскрізна тріщина в широкій пластині (Y = 1,12)' : 'центральна наскрізна тріщина в широкій пластині (Y = 1,0); загальна довжина тріщини 2a = ' + fmt(2 * v.amm) + ' мм';
    b.push(H('Вихідні дані варіанта'));
    b.push(INFO(`<p>Під час дефектоскопії елемента конструкції виявлено тріщину нормального відриву (мода I): <b>${G}</b>. Номінальне напруження розтягу σ діє перпендикулярно до площини тріщини. Навантаження пульсуюче (R = 0), розмах Δσ = σ.</p>`));
    b.push(TABLE(['σ, МПа', v.geo === 'edge' ? 'a, мм' : '2a, мм', 'Y', 'K<sub>IC</sub>, МПа√м', 'σ<sub>0,2</sub>, МПа', 'B, мм'],
      [[v.sigma, fmt(v.geo === 'edge' ? v.amm : 2 * v.amm), String(v.Y).replace('.', ','), v.KIC, v.sy, v.B]]));
    b.push(INFO(`<p class="note">Навчальні дані варіанта. Закон Паріса для феритно-перлітних сталей (Barsom): da/dN = C(ΔK)<sup>m</sup>, C = 6,9·10<sup>−12</sup> м/цикл·(МПа√м)<sup>−3</sup>, m = 3. Нормативний запас за тріщиностійкістю [n<sub>K</sub>] = 1,5. Розмір пластичної зони — за Ірвіном для плоского напруженого стану: r<sub>p</sub> = (1/2π)(K<sub>I</sub>/σ<sub>0,2</sub>)². Перевірка плоскої деформації: B ≥ 2,5(K<sub>IC</sub>/σ<sub>0,2</sub>)².</p>`));
    const C8 = ['ФК.08', 'ЗК.01'];
    b.push(H('1. Коефіцієнт інтенсивності напружень і запас'));
    b.push(NUM('p2_a', 'Розрахункова довжина тріщини a в СІ', v.a, { unit: 'м', tol: 0.005, comp: ['ФК.08'],
      errors: [{ value: v.geo === 'center' ? 2 * v.a : NaN, msg: 'Для центральної тріщини у формулу K<sub>I</sub> підставляють півдовжину a, а не 2a' }] }));
    b.push(NUM('p2_K', 'K<sub>I</sub> = Yσ√(πa)', v.K, { unit: 'МПа√м', comp: C8,
      errors: [{ value: v.geo === 'center' ? v.Y * v.sigma * Math.sqrt(Math.PI * 2 * v.a) : NaN, msg: 'Підставлено 2a замість півдовжини a' }, { value: v.sigma * Math.sqrt(Math.PI * v.a), msg: 'Не враховано геометричний коефіцієнт Y' }, { value: v.Y * v.sigma * Math.sqrt(v.a), msg: 'Пропущено π під коренем' }] }));
    b.push(NUM('p2_nK', 'Запас тріщиностійкості n<sub>K</sub> = K<sub>IC</sub>/K<sub>I</sub>', v.nK, { comp: ['ФК.08'], errors: [{ value: 1 / v.nK, msg: 'Запас обернено: n<sub>K</sub> = K<sub>IC</sub>/K<sub>I</sub>' }] }));
    b.push(H('2. Критичні параметри'));
    b.push(NUM('p2_sc', 'Критичне напруження σ<sub>c</sub> для наявної тріщини', v.sc, { unit: 'МПа', comp: C8 }));
    b.push(NUM('p2_ac', 'Критична довжина тріщини a<sub>c</sub> за номінального σ' + (v.geo === 'center' ? ' (півдовжина)' : ''), v.ac, { unit: 'мм', comp: C8,
      errors: [{ value: v.ac / 1000, msg: 'Результат отримано в метрах — потрібно в мм' }, { value: (v.KIC / (v.Y * v.sigma)) ** 2 * 1000, msg: 'Пропущено ділення на π: a<sub>c</sub> = (1/π)(K<sub>IC</sub>/Yσ)²' }, { value: v.geo === 'center' ? 2 * v.ac : NaN, msg: 'Подано повну довжину 2a<sub>c</sub>, а потрібна півдовжина' }] }));
    b.push(NUM('p2_sadm', 'Допустиме напруження за умови [n<sub>K</sub>] = 1,5', v.sadm, { unit: 'МПа', comp: ['ФК.08', 'ЗК.03'], errors: [{ value: v.sc * 1.5, msg: 'Критичне напруження потрібно ділити на запас, а не множити' }] }));
    b.push(H('3. Межі застосовності ЛМР'));
    b.push(NUM('p2_rp', 'Розмір пластичної зони r<sub>p</sub> (Ірвін, ПНС)', v.rp, { unit: 'мм', comp: C8,
      errors: [{ value: v.rp / 3, msg: 'Використано формулу для плоскої деформації (1/6π) замість ПНС (1/2π)' }] }));
    b.push(NUM('p2_Bmin', 'Мінімальна товщина для плоскої деформації B<sub>min</sub>', v.Bmin, { unit: 'мм', comp: C8 }));
    const valid = v.B >= v.Bmin;
    b.push(CHOICE(r, 'p2_valid', 'Чи коректно використовувати K<sub>IC</sub> (ЛМР) для елемента товщиною B = ' + v.B + ' мм?', [
      { t: 'Так: B ≥ B<sub>min</sub>, умови плоскої деформації виконуються, ЛМР застосовна', ok: valid, why: 'Порівняйте B з B<sub>min</sub>' },
      { t: 'Ні: B < B<sub>min</sub> — тріщиностійкість залежить від товщини, доцільна оцінка за J-інтегралом / CTOD (ПМР)', ok: !valid, why: 'Порівняйте B з B<sub>min</sub>' },
    ], { comp: ['ЗК.03', 'ФК.02'] }));
    b.push(H('4. Стабільний ріст тріщини (закон Паріса)'));
    if (v.ac > v.amm) {
      b.push(NUM('p2_Np', 'Кількість циклів росту тріщини від a до a<sub>c</sub>', v.Np, { unit: 'циклів', tol: 0.03, comp: ['ФК.08', 'ФК.07'] }));
    } else {
      b.push(INFO('<p>У вашому варіанті a ≥ a<sub>c</sub>: стадії стабільного росту немає, тож підрахунок циклів за законом Паріса не виконується.</p>'));
    }
    b.push(H('5. Інженерне рішення'));
    const dec = v.nK >= v.nadm ? 0 : v.nK >= 1 ? 1 : 2;
    b.push(CHOICE(r, 'p2_dec', 'Рішення щодо подальшої експлуатації:', [
      { t: 'Експлуатація допустима: n<sub>K</sub> ≥ [n<sub>K</sub>], тріщину контролювати під час регламентних оглядів', ok: dec === 0 },
      { t: 'Експлуатація можлива лише з обмеженням навантаження до σ<sub>adm</sub> та скороченим інтервалом дефектоскопії', ok: dec === 1 },
      { t: 'Експлуатація недопустима: K<sub>I</sub> ≥ K<sub>IC</sub>, прогнозується нестабільне руйнування — ремонт/заміна', ok: dec === 2 },
    ], { comp: ['ЗК.03', 'ФК.07'], w: 1.5 }));
    b.push(TEXT('p2_just', 'Інженерний висновок: оцініть запас, межі застосовності ЛМР і запропонуйте, чим верифікувати результат (3–5 речень).', { comp: ['ЗК.03', 'ФК.02'] }));
    b.push(H('6. Контрольні запитання'));
    b.push(...theory(r, 'p2', [
      { q: 'Одиниці коефіцієнта інтенсивності напружень K<sub>I</sub>:', ok: 'МПа·√м', bad: ['МПа·м', 'МПа/м', 'Н/м'] },
      { q: 'Що характеризує K<sub>IC</sub>?', ok: 'Критичне значення K<sub>I</sub> в умовах плоскої деформації — властивість матеріалу (в\'язкість руйнування)', bad: ['Геометрію тріщини', 'Границю текучості матеріалу', 'Швидкість росту втомної тріщини'] },
      { q: 'Чим J-інтеграл відрізняється від K?', ok: 'J — енергетичний параметр, придатний і для пружно-пластичного деформування біля вершини тріщини', bad: ['J застосовний лише в пружній області', 'J характеризує тільки моду III', 'Різниці немає, це синоніми'] },
      { q: 'Що описує мода I?', ok: 'Нормальний відрив: навантаження перпендикулярне площині тріщини', bad: ['Поперечний зсув', 'Поздовжній (антиплощинний) зсув', 'Стиск берегів тріщини'] },
      { q: 'Умова застосовності ЛМР:', ok: 'Пластична зона мала порівняно з довжиною тріщини і розмірами перерізу', bad: ['Будь-який розмір пластичної зони', 'Лише для крихких полімерів', 'Тільки при циклічному навантаженні'] },
      { q: 'CTOD — це:', ok: 'Розкриття вершини тріщини — деформаційний параметр ПМР', bad: ['Критична температура крихкості', 'Коефіцієнт концентрації напружень', 'Швидкість росту тріщини за цикл'] },
    ], 3));
    return b;
  },
  review(v) {
    const as = linspace(0.5, Math.max(v.ac, v.amm) * 1.4, 80);
    const c1 = plot({ id: 21, title: 'K_I(a) за номінального напруження і критична довжина тріщини', xlab: 'a, мм', ylab: 'K_I, МПа√м',
      series: [{ pts: as.map(x => [x, v.Y * v.sigma * Math.sqrt(Math.PI * x / 1000)]), color: COL.s1, label: 'K_I(a)' }, { pts: [[v.amm, v.K]], line: false, marker: true, color: COL.s2, label: 'поточна тріщина' }],
      xmin: 0, ymin: 0, hlines: [{ y: v.KIC, label: 'K_IC = ' + v.KIC }], vlines: [{ x: v.ac, label: 'a_c = ' + fmtT(v.ac, 3) + ' мм' }] });
    return [c1];
  },
});
